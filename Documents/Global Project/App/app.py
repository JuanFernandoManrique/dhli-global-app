from flask import Flask, render_template, request
import pickle
import pandas as pd
import numpy as np
import os
from sklearn.preprocessing import StandardScaler

app = Flask(__name__)

# Cargar los modelos SVM y el scaler
try:
    with open('modelo_ENm.pkl', 'rb') as file:
        modelo_ENm = pickle.load(file)
    with open('modelo_ENg.pkl', 'rb') as file:
        modelo_ENg = pickle.load(file)
    with open('scaler.pkl', 'rb') as file:
        scaler = pickle.load(file)
except FileNotFoundError:
    print("Error: No se encontraron los archivos del modelo o el scaler.")
    exit()

# Cargar los modelos lineales, las métricas y las ecuaciones
modelos_lineales = {}
for variable in ['EMm', 'EMg', 'EDm', 'EDg']:
    try:
        with open(f'modelo_{variable}.pkl', 'rb') as file:
            modelos_lineales[variable] = pickle.load(file)
    except FileNotFoundError:
        print(f"Error: No se encontraron los archivos para el modelo lineal {variable}.")
        exit()

@app.route('/', methods=['GET', 'POST'])
def index():
    resultados = {}  # Inicializar el diccionario de resultados
    if request.method == 'POST':
        try:
            pv = float(request.form['pv'])
            ganancia = float(request.form['ganancia'])

            # Crear DataFrame con los datos de entrada
            input_data = pd.DataFrame({'PV(g)': [pv], 'Ganancia(g)': [ganancia]})

            # Escalar los datos de entrada usando el mismo scaler
            scaled_input_data = scaler.transform(input_data)

            # Predecir ENm y ENg con los modelos SVM
            ENm = modelo_ENm.predict(scaled_input_data)[0]
            ENg = modelo_ENg.predict(scaled_input_data)[0]

            # Utilizar los modelos lineales sencillos para predecir EMm, EMg, EDm y EDg
            EMm = modelos_lineales['EMm'].predict(np.array([[ENm]]))[0]
            EMg = modelos_lineales['EMg'].predict(np.array([[ENg]]))[0]
            EDm = modelos_lineales['EDm'].predict(np.array([[ENm]]))[0]
            EDg = modelos_lineales['EDg'].predict(np.array([[ENg]]))[0]

            # Guardar los resultados en un diccionario para mostrarlos en la plantilla
            resultados = {
                'pv': pv,
                'ganancia': ganancia,
                'ENm': ENm,
                'ENg': ENg,
                'EMm': EMm,
                'EMg': EMg,
                'EDm': EDm,
                'EDg': EDg
            }

            return render_template('index.html', resultados=resultados)

        except ValueError:
            return render_template('index.html', error='Por favor, ingresa valores numéricos válidos.')

    return render_template('index.html', resultados=resultados)

if __name__ == '__main__':
    app.run(debug=True, host='0.0.0.0', port=int(os.environ.get('PORT', 8000)))  # Modifica esta línea